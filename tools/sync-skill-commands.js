/* Expose every installed skill as an OpenCode command.
 *
 * OpenCode discovers commands from `.opencode/commands/*.md` and skills from
 * `.agents/skills/<id>/SKILL.md`. A command is only a prompt template, so the
 * bridge between the two is one sentence: load the skill, then follow it.
 *
 * Run it after installing or removing skills:
 *
 *   node tools/sync-skill-commands.js
 *
 * The script is idempotent. It rewrites only the files it owns and leaves any
 * hand-written command in `.opencode/commands` alone.
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const skillsDir = path.join(root, ".agents", "skills");
const commandsDir = path.join(root, ".opencode", "commands");
const banner = "<!-- Generated by tools/sync-skill-commands.js. Do not edit by hand. -->";

/* Match the line endings the repo already uses, so a diff of a regenerated
 * command is a diff of content and nothing else. */
const eol = fs.readFileSync(path.join(root, "README.md"), "utf8").includes("\r\n") ? "\r\n" : "\n";

/* The frontmatter is YAML, so a description is either a plain scalar or a
 * quoted one. Quoted values arrive with their escapes still in place, and a
 * plain scalar may legally contain a colon — so both are normalised back to a
 * plain string before they are re-emitted as a quoted scalar. */
function unquote(value) {
  const text = value.trim();
  if (text.startsWith('"') && text.endsWith('"') && text.length > 1) {
    return text.slice(1, -1).replace(/\\(["\\])/g, "$1");
  }
  if (text.startsWith("'") && text.endsWith("'") && text.length > 1) {
    return text.slice(1, -1).replace(/''/g, "'");
  }
  return text;
}

function yamlQuote(value) {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function readFrontmatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!match) return null;
  const frontmatter = match[1];
  const name = /^name:\s*(.+)$/m.exec(frontmatter);
  const description = /^description:\s*([\s\S]*?)(?=\n[A-Za-z_-]+:|$)/m.exec(frontmatter);
  return {
    name: name ? unquote(name[1]) : "",
    description: description ? unquote(description[1]) : "",
  };
}

function buildCommand(id, description) {
  const summary = description || `Run the ${id} skill`;
  return [
    "---",
    `description: ${yamlQuote(summary.replace(/\r?\n/g, " "))}`,
    "---",
    "",
    banner,
    "",
    `Load the \`${id}\` skill with the skill tool (id: \`${id}\`) and follow its instructions.`,
    "",
    "$ARGUMENTS",
    "",
  ].join(eol);
}

function main() {
  if (!fs.existsSync(skillsDir)) {
    console.error(`No skills directory at ${skillsDir}.`);
    process.exitCode = 1;
    return;
  }
  fs.mkdirSync(commandsDir, { recursive: true });

  const ids = fs
    .readdirSync(skillsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((id) => fs.existsSync(path.join(skillsDir, id, "SKILL.md")))
    .sort();

  let written = 0;
  for (const id of ids) {
    const text = fs.readFileSync(path.join(skillsDir, id, "SKILL.md"), "utf8");
    const frontmatter = readFrontmatter(text);
    fs.writeFileSync(path.join(commandsDir, `${id}.md`), buildCommand(id, frontmatter?.description || ""), "utf8");
    written += 1;
  }

  // Drop command files this script wrote for skills that no longer exist.
  const stale = fs
    .readdirSync(commandsDir)
    .filter((file) => file.endsWith(".md") && file !== "README.md")
    .filter((file) => !ids.includes(path.basename(file, ".md")));
  for (const file of stale) fs.rmSync(path.join(commandsDir, file));

  console.log(`${written} skill command(s) written to .opencode/commands${stale.length ? `, ${stale.length} stale removed` : ""}.`);
}

main();
